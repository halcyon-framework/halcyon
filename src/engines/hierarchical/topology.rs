// =============================================================================
// SPEC-HAL-259: HierarchicalRowTopology — Hierarchical Topology Engine
// =============================================================================
//
// Implements TopologyEngine with tree-structured row ordering.
// Owns parent/child relationships, expansion state, depth, and
// deterministic projection ordering.
//
// Expansion/collapse invalidates topology through engine-owned gating
// (topology_dirty + tree_dirty), not substrate-side epoch hacks.
//
// INVARIANT-RT-1: Must not reference column geometry.
// INVARIANT-RT-2: Must not own or mutate selection state.
// INVARIANT-RT-3: Must not depend on scroll offset.
// INVARIANT-RT-4: Must not perform virtualization windowing.
//
// INVARIANT-HTS-PREORDER: self.nodes is stored in strict pre-order traversal
// order. For any node at index i with parent_index = Some(p): p < i.
// All descendants of a node at index i appear in a contiguous range
// (i+1..j) where j is the first index with depth <= nodes[i].depth.
// This invariant is load-bearing for: subtree scan (expand_subtree,
// collapse_subtree), compute_visible_indices, compute_guide_caches,
// is_row_visible. Debug-asserted in set_tree_data().
// =============================================================================

use std::collections::HashMap;

use crate::engines::row_topology::TopologyEngine;

/// Per-row tree node metadata for hierarchical topology.
///
/// SPEC-HAL-259 §5.2: Owned by the topology engine (not external projection).
/// Defines the parent/child structure and intrinsic node properties.
#[derive(Debug, Clone)]
pub struct NodeMeta {
    /// Caller-assigned stable node identifier.
    /// INV-NODE-ID-CALLER: Assigned by caller, never generated by engine.
    pub node_id: u64,
    /// Parent row index (None for root nodes).
    pub parent_index: Option<usize>,
    /// Tree depth (0 for root nodes).
    pub depth: u32,
    /// Whether this node has children.
    pub has_children: bool,
    /// Display label for this node.
    pub label: String,
}

/// Hierarchical row topology engine.
///
/// SPEC-HAL-259 §5.2: Implements TopologyEngine with hierarchical row ordering.
/// Owns expansion state, parent/child relationships, depth, and stable
/// deterministic projection ordering.
///
/// Expansion/collapse invalidates topology through engine-owned gating
/// (topology_dirty + tree_dirty), not substrate-side epoch hacks.
///
/// INV-HTS-004: Topology changes do not force column geometry recompute.
///
/// ## Epoch Semantics (Coherence Note)
///
/// `base_row_order_epoch` means "physical row model structural change"
/// (new rows added/removed). Tree reshaping (set_tree_data, expand,
/// collapse) flows through `tree_dirty + topology_dirty` instead,
/// NOT through base epoch bumps. This is intentional: the hierarchical
/// engine owns tree structure internally, and tree mutations are a
/// projection concern, not a physical row identity concern.
///
/// This diverges from flat RowTopologyEngine where base epoch is bumped
/// by external row model mutations. Both engines agree on the semantic:
/// base_row_order_epoch = physical row model change only.
#[derive(Debug)]
pub(crate) struct HierarchicalRowTopology {
    // --- TopologyEngine state ---
    sorted_indices: Vec<usize>,
    sorted_indices_epoch: u64,
    base_row_order_epoch: u64,
    topology_version: u64,
    topology_dirty: bool,

    // --- Hierarchical state (engine-owned) ---
    /// Per-row tree metadata (indexed by physical row index).
    nodes: Vec<NodeMeta>,
    /// Per-row expansion state (indexed by physical row index).
    expanded: Vec<bool>,
    /// Cached visible row indices (computed from expansion state).
    visible_indices: Vec<usize>,
    /// Per-row guide mask: bit `d` set means "draw vertical continuation line at depth d".
    ///
    /// Indexed by physical row index (parallel to nodes[]).
    /// Computed in O(n) per recompute alongside visible_indices.
    guide_masks: Vec<u64>,
    /// Per-row stem-down flag: true when node is expanded and has children.
    ///
    /// Indicates "draw vertical stem down from this node at its depth level".
    /// Indexed by physical row index (parallel to nodes[]).
    stem_down_flags: Vec<bool>,
    /// Whether tree projection needs recomputation.
    tree_dirty: bool,

    /// O(1) reverse lookup: node_id → physical row index.
    /// INV-NODE-ID-REBUILD: Rebuilt on every set_tree_data().
    node_id_to_index: HashMap<u64, usize>,
}

impl HierarchicalRowTopology {
    pub(crate) fn new() -> Self {
        Self {
            sorted_indices: Vec::new(),
            sorted_indices_epoch: 0,
            base_row_order_epoch: 1,
            topology_version: 0,
            topology_dirty: true,
            nodes: Vec::new(),
            expanded: Vec::new(),
            visible_indices: Vec::new(),
            guide_masks: Vec::new(),
            stem_down_flags: Vec::new(),
            tree_dirty: false,
            node_id_to_index: HashMap::new(),
        }
    }

    /// Set tree metadata for all rows.
    ///
    /// Replaces the entire tree structure. Initial expansion state: nodes with
    /// children start expanded.
    ///
    /// Invalidation: sets tree_dirty + topology_dirty → engine-owned gating
    /// triggers recompute on next ensure_sorted_order call.
    pub(crate) fn set_tree_data(&mut self, nodes: Vec<NodeMeta>) {
        // INV-NODE-ID-UNIQUE: Each node_id appears at most once (debug-validated).
        #[cfg(debug_assertions)]
        {
            let mut seen = std::collections::HashSet::with_capacity(nodes.len());
            for (i, node) in nodes.iter().enumerate() {
                assert!(
                    seen.insert(node.node_id),
                    "INV-NODE-ID-UNIQUE: duplicate node_id {} at index {}",
                    node.node_id,
                    i
                );
            }
        }

        // INV-NODE-ID-REBUILD: Rebuild reverse map atomically.
        self.node_id_to_index.clear();
        for (i, node) in nodes.iter().enumerate() {
            self.node_id_to_index.insert(node.node_id, i);
        }

        self.expanded = nodes.iter().map(|n| n.has_children).collect();
        self.nodes = nodes;
        self.tree_dirty = true;
        self.topology_dirty = true;

        #[cfg(debug_assertions)]
        self.assert_preorder_invariant();
    }

    /// Clear tree metadata.
    #[allow(dead_code, reason = "Retained topology reset with cache invalidation")]
    pub(crate) fn clear_tree_data(&mut self) {
        self.nodes.clear();
        self.expanded.clear();
        self.node_id_to_index.clear();
        self.visible_indices.clear();
        self.guide_masks.clear();
        self.stem_down_flags.clear();
        self.tree_dirty = true;
        self.topology_dirty = true;
    }

    /// Expand a node (make its children visible).
    ///
    /// Invalidates through engine-owned gating (topology_dirty).
    pub(crate) fn expand(&mut self, row_index: usize) {
        if let Some(node) = self.nodes.get(row_index) {
            if node.has_children && !self.expanded[row_index] {
                self.expanded[row_index] = true;
                self.tree_dirty = true;
                self.topology_dirty = true;
            }
        }
    }

    /// Collapse a node (hide its children).
    ///
    /// Invalidates through engine-owned gating (topology_dirty).
    pub(crate) fn collapse(&mut self, row_index: usize) {
        if let Some(node) = self.nodes.get(row_index) {
            if node.has_children && self.expanded[row_index] {
                self.expanded[row_index] = false;
                self.tree_dirty = true;
                self.topology_dirty = true;
            }
        }
    }

    /// Toggle a node's expansion state.
    ///
    /// Invalidates through engine-owned gating (topology_dirty).
    pub(crate) fn toggle(&mut self, row_index: usize) {
        if let Some(node) = self.nodes.get(row_index) {
            if node.has_children {
                self.expanded[row_index] = !self.expanded[row_index];
                self.tree_dirty = true;
                self.topology_dirty = true;
            }
        }
    }

    /// Recursively expand a node and all its descendants.
    ///
    /// Depth-based contiguous forward scan: iterates nodes after row_index
    /// until depth drops back to root level. O(k) where k = subtree size.
    /// Single invalidation if anything changed. Returns true if any node
    /// was expanded.
    pub(crate) fn expand_subtree(&mut self, row_index: usize) -> bool {
        if row_index >= self.nodes.len() {
            return false;
        }
        let root_depth = self.nodes[row_index].depth;
        let mut changed = false;

        // Expand root node itself.
        if self.nodes[row_index].has_children && !self.expanded[row_index] {
            self.expanded[row_index] = true;
            changed = true;
        }

        // Forward scan: expand all descendants.
        for i in (row_index + 1)..self.nodes.len() {
            if self.nodes[i].depth <= root_depth {
                break;
            }
            if self.nodes[i].has_children && !self.expanded[i] {
                self.expanded[i] = true;
                changed = true;
            }
        }

        if changed {
            self.tree_dirty = true;
            self.topology_dirty = true;
        }
        changed
    }

    /// Recursively collapse a node and all its descendants.
    ///
    /// Depth-based contiguous forward scan: collapses all descendants first,
    /// then collapses the root node itself. O(k) where k = subtree size.
    /// Single invalidation if anything changed. Returns true if any node
    /// was collapsed.
    pub(crate) fn collapse_subtree(&mut self, row_index: usize) -> bool {
        if row_index >= self.nodes.len() {
            return false;
        }
        let root_depth = self.nodes[row_index].depth;
        let mut changed = false;

        // Forward scan: collapse all descendants first.
        // Uses expanded[i] alone — has_children is redundant since expanded
        // is only set true for nodes with children (set_tree_data initializes
        // expanded from has_children; expand/toggle guard on has_children).
        for i in (row_index + 1)..self.nodes.len() {
            if self.nodes[i].depth <= root_depth {
                break;
            }
            if self.expanded[i] {
                self.expanded[i] = false;
                changed = true;
            }
        }

        // Collapse root node itself.
        if self.nodes[row_index].has_children && self.expanded[row_index] {
            self.expanded[row_index] = false;
            changed = true;
        }

        if changed {
            self.tree_dirty = true;
            self.topology_dirty = true;
        }
        changed
    }

    /// Get node metadata for a row.
    pub(crate) fn node_meta(&self, row_index: usize) -> Option<&NodeMeta> {
        self.nodes.get(row_index)
    }

    /// Get tree depth for a row.
    ///
    /// Returns the stored depth directly (0 for roots, 1 for their children, etc.).
    pub(crate) fn depth(&self, row_index: usize) -> u32 {
        self.nodes.get(row_index).map_or(0, |n| n.depth)
    }

    /// Check if a row is expanded.
    pub(crate) fn is_expanded(&self, row_index: usize) -> bool {
        self.expanded.get(row_index).copied().unwrap_or(false)
    }

    /// Check if a row has children.
    pub(crate) fn has_children(&self, row_index: usize) -> bool {
        self.nodes.get(row_index).map_or(false, |n| n.has_children)
    }

    /// Get the guide mask for a row.
    ///
    /// Bit `d` set means "draw vertical continuation line at depth d".
    /// Returns 0 for inactive/out-of-range indices.
    pub(crate) fn guide_mask(&self, row_index: usize) -> u64 {
        self.guide_masks.get(row_index).copied().unwrap_or(0)
    }

    /// Get the stem-down flag for a row.
    ///
    /// True means "draw vertical stem down from this node at its depth level"
    /// (the node is expanded and has children).
    /// Returns false for inactive/out-of-range indices.
    pub(crate) fn stem_down(&self, row_index: usize) -> bool {
        self.stem_down_flags
            .get(row_index)
            .copied()
            .unwrap_or(false)
    }

    /// Get the label for a row.
    pub(crate) fn label(&self, row_index: usize) -> &str {
        self.nodes.get(row_index).map_or("", |n| &n.label)
    }

    /// Get caller-assigned node_id for a physical row index.
    pub(crate) fn node_id(&self, row_index: usize) -> u64 {
        self.nodes[row_index].node_id
    }

    /// Reverse lookup: node_id → physical row index.
    pub(crate) fn index_for_id(&self, node_id: u64) -> Option<usize> {
        self.node_id_to_index.get(&node_id).copied()
    }

    /// Whether tree data is loaded.
    pub(crate) fn is_tree_active(&self) -> bool {
        !self.nodes.is_empty()
    }

    /// Number of nodes in the tree.
    pub(crate) fn node_count(&self) -> usize {
        self.nodes.len()
    }

    /// Compute visible row indices and guide caches from current expansion state.
    ///
    /// A row is visible if all ancestors up to root are expanded.
    /// Root nodes are visible rows (not hidden structural anchors).
    /// Also computes guide_masks and stem_down_flags (O(n) total).
    fn compute_visible_indices(&mut self, row_count: usize) {
        self.visible_indices.clear();
        let limit = row_count.min(self.nodes.len());
        for i in 0..limit {
            if self.is_row_visible(i) {
                self.visible_indices.push(i);
            }
        }
        self.compute_guide_caches();
        self.tree_dirty = false;
    }

    /// Compute guide_masks and stem_down_flags for all nodes.
    ///
    /// Algorithm (O(n) total — no per-query ancestor walks):
    /// 1. Reverse pass: determine last-child status for each node.
    /// 2. Forward pass: compute guide_masks top-down by inheriting parent mask.
    /// 3. Linear pass: compute stem_down from expanded + has_children.
    ///
    /// ## guide_mask bit semantics
    ///
    /// For node `i` at depth `D` with parent `p` at depth `D-1`:
    ///
    /// - Bits 0..D-2 (ancestor lanes): inherited from parent's mask.
    ///   Bit `d` set means the ancestor at depth `d+1` is NOT the last child
    ///   of the ancestor at depth `d` — draw vertical continuation at lane `d`.
    ///
    /// - Bit D-1 (parent connector lane): set if node `i` is NOT the last
    ///   child of parent `p` — draw tee (├). Clear if node `i` IS the last
    ///   child — draw elbow (└).
    ///
    /// The mask is inherited top-down: each child starts with its parent's mask
    /// and adds bit `parent.depth` based on its OWN last-child status.
    fn compute_guide_caches(&mut self) {
        let n = self.nodes.len();
        if n == 0 {
            self.guide_masks.clear();
            self.stem_down_flags.clear();
            return;
        }

        // Phase 1: Determine last-child status per node.
        // Reverse pass: first node seen (in reverse) for each parent = last child.
        let mut is_last_child = vec![false; n];
        let mut seen_child_of: Vec<bool> = vec![false; n];
        let mut seen_root_group = false;

        for i in (0..n).rev() {
            let effective_parent = match self.nodes[i].parent_index {
                Some(p) if p < n && p < i => Some(p),
                _ => None,
            };
            match effective_parent {
                None => {
                    if !seen_root_group {
                        is_last_child[i] = true;
                        seen_root_group = true;
                    }
                }
                Some(p) => {
                    if !seen_child_of[p] {
                        is_last_child[i] = true;
                        seen_child_of[p] = true;
                    }
                }
            }
        }

        // Phase 2: Compute guide masks top-down.
        //
        // Each child inherits parent's mask (ancestor continuation bits) and adds
        // the parent-connector bit based on whether THIS CHILD is the last sibling.
        self.guide_masks.clear();
        self.guide_masks.resize(n, 0);

        for i in 0..n {
            let effective_parent = match self.nodes[i].parent_index {
                Some(p) if p < n && p < i => Some(p),
                _ => None,
            };
            self.guide_masks[i] = match effective_parent {
                None => 0,
                Some(p) => {
                    let mut mask = self.guide_masks[p];
                    if !is_last_child[i] {
                        mask |= 1u64 << self.nodes[p].depth.min(63);
                    }
                    mask
                }
            };
        }

        // Phase 3: Compute stem_down flags.
        self.stem_down_flags.clear();
        self.stem_down_flags.resize(n, false);
        for i in 0..n {
            self.stem_down_flags[i] = self.nodes[i].has_children && self.expanded[i];
        }
    }

    /// Debug-only: validate INVARIANT-HTS-PREORDER.
    ///
    /// Asserts that self.nodes is in strict pre-order:
    /// - Every parent_index < own index.
    /// - Child depth == parent depth + 1 (strict tree level).
    /// - Root nodes (parent_index == None) have depth == 0.
    ///
    /// Called from set_tree_data() only. No runtime overhead in release.
    #[cfg(debug_assertions)]
    fn assert_preorder_invariant(&self) {
        for (i, node) in self.nodes.iter().enumerate() {
            if let Some(p) = node.parent_index {
                assert!(
                    p < i,
                    "INV-HTS-PREORDER: node {} has parent_index {} (must be < {})",
                    i,
                    p,
                    i
                );
                assert_eq!(
                    node.depth,
                    self.nodes[p].depth + 1,
                    "INV-HTS-PREORDER: node {} depth {} must equal parent {} depth {} + 1",
                    i,
                    node.depth,
                    p,
                    self.nodes[p].depth
                );
            } else {
                assert_eq!(
                    node.depth, 0,
                    "INV-HTS-PREORDER: root node {} must have depth 0",
                    i
                );
            }
        }
    }

    /// Check if a row is visible (all ancestors expanded).
    fn is_row_visible(&self, index: usize) -> bool {
        let node = &self.nodes[index];
        let mut current_parent = node.parent_index;
        let mut current_index = index;
        while let Some(parent_idx) = current_parent {
            if parent_idx >= self.nodes.len() || parent_idx >= current_index {
                break; // invalid/backward reference → treat as root
            }
            if !self.expanded[parent_idx] {
                return false;
            }
            current_index = parent_idx;
            current_parent = self.nodes[parent_idx].parent_index;
        }
        true
    }
}

impl TopologyEngine for HierarchicalRowTopology {
    fn sorted_indices(&self) -> &[usize] {
        &self.sorted_indices
    }

    fn topology_version(&self) -> u64 {
        self.topology_version
    }

    fn base_row_order_epoch(&self) -> u64 {
        self.base_row_order_epoch
    }

    fn sorted_indices_epoch(&self) -> u64 {
        self.sorted_indices_epoch
    }

    fn is_topology_dirty(&self) -> bool {
        self.topology_dirty
    }

    fn set_sorted_indices(&mut self, indices: Vec<usize>, row_count: usize) {
        self.validate_permutation(&indices, row_count);
        self.sorted_indices = indices;
        self.topology_version += 1;
    }

    fn increment_base_epoch(&mut self) {
        self.base_row_order_epoch += 1;
        self.sorted_indices_epoch = 0;
    }

    #[cfg(test)]
    fn set_topology_dirty(&mut self, dirty: bool) {
        self.topology_dirty = dirty;
    }

    /// Ensure sorted order is current.
    ///
    /// SPEC-HAL-259: Hierarchical topology owns tree state internally.
    /// The `tree_visible_indices` parameter is IGNORED — this engine computes
    /// visible indices from its own expansion state.
    ///
    /// Engine owns ALL gating (SPEC-HAL-258):
    /// topology_dirty, tree_dirty, epoch mismatch, length mismatch, sort_dirty.
    fn ensure_sorted_order(
        &mut self,
        row_count: usize,
        _tree_visible_indices: Option<&[usize]>,
        sort_dirty: bool,
        sorter: &dyn Fn(&mut [usize]),
    ) -> bool {
        // Recompute visible indices from tree state if tree is dirty.
        if self.tree_dirty {
            self.compute_visible_indices(row_count);
        }

        let effective_base_count = if self.is_tree_active() {
            self.visible_indices.len()
        } else {
            row_count
        };

        let needs_recompute = self.topology_dirty
            || sort_dirty
            || self.sorted_indices_epoch != self.base_row_order_epoch
            || self.sorted_indices.len() != effective_base_count;

        if needs_recompute {
            let mut indices: Vec<usize> = if self.is_tree_active() {
                self.visible_indices.clone()
            } else {
                (0..row_count).collect()
            };

            sorter(&mut indices);

            debug_assert!(
                indices.iter().all(|&idx| idx < row_count),
                "SPEC-HAL-259: ensure_sorted_order produced invalid index (row_count={})",
                row_count
            );

            self.sorted_indices = indices;
            self.sorted_indices_epoch = self.base_row_order_epoch;
            self.topology_version += 1;
        }

        self.topology_dirty = false;
        needs_recompute
    }

    fn logical_row_count(&self, substrate_count: usize) -> usize {
        if self.is_tree_active() {
            self.visible_indices.len()
        } else {
            substrate_count
        }
    }

    fn compute_sorted_row_count(&self, base_row_count: usize, _tree_active: bool) -> usize {
        if self.is_tree_active() {
            self.visible_indices.len()
        } else {
            base_row_count
        }
    }

    fn should_realize(&self, virtualization_dirty: bool) -> bool {
        virtualization_dirty
    }

    fn on_realized(&mut self) {}

    /// Validate indices are a valid subset of 0..row_count.
    ///
    /// Unlike flat topology (which validates a full permutation), hierarchical
    /// topology produces a SUBSET of visible rows. All indices must be unique
    /// and within bounds, but count may be less than row_count.
    fn validate_permutation(&self, indices: &[usize], row_count: usize) {
        debug_assert!(
            indices.len() <= row_count,
            "INV-HTS-ORDERING: length {} exceeds row_count {}",
            indices.len(),
            row_count
        );

        #[cfg(debug_assertions)]
        {
            let mut seen = vec![false; row_count];
            for &i in indices {
                assert!(
                    i < row_count,
                    "INV-HTS-ORDERING: index {} out of range (row_count={})",
                    i,
                    row_count
                );
                assert!(!seen[i], "INV-HTS-ORDERING: duplicate index {}", i);
                seen[i] = true;
            }
        }
    }
}
